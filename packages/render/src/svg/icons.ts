/** Drawn for an unknown name: a plain ring, so the slot keeps its size. */
const FALLBACK = '<circle cx="12" cy="12" r="8"/>';

/** The paths for `name`, or `undefined` when no icon has that name. */
export function iconPaths(name: string): string | undefined {
  return isIconName(name) ? ICONS[name] : undefined;
}

/**
 * One icon as an inline `<svg>`; an unknown name draws the fallback ring.
 *
 * With `label`, the icon is an image with that accessible name (an inline
 * `:name:` in text, which may carry the whole meaning of a table cell).
 * Without it, the icon is decoration beside its words and is hidden from
 * assistive technology.
 */
export function iconSvg(name: string, cls?: string, label?: string): string {
  const klass = cls !== undefined ? ` class="${cls}"` : '';
  const a11y = label !== undefined ? ` role="img" aria-label="${escapeHtml(label)}"` : ' aria-hidden="true"';
  return `<svg${klass} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"${a11y}>${iconPaths(name) ?? FALLBACK}</svg>`;
}

/** An inline icon in text: sized to the text (`.ic`) and named for a screen reader. */
export function inlineIconSvg(name: IconName): string {
  return iconSvg(name, 'ic', iconLabel(name));
}
